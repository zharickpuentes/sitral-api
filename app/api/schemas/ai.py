from pydantic import BaseModel, ConfigDict, Field

from app.application.asistente.prompts import Tecnica


class ConsultaIARequest(BaseModel):
    """Natural-language question about inventory, batches or expiry alerts."""

    model_config = ConfigDict(json_schema_extra={"examples": [{
        "pregunta": "¿Qué lotes vencen en los próximos 10 días y qué debo hacer con cada uno?",
        "tecnica": "cot", "top_k": 8, "incluir_prompt": False,
    }]})

    pregunta: str = Field(..., min_length=5, max_length=500, description="Question in Spanish.")
    tecnica: Tecnica = Field(Tecnica.ZERO_SHOT, description="Prompting technique: zero_shot, few_shot or cot.")
    top_k: int = Field(8, ge=1, le=20, description="Number of inventory documents retrieved by RAG.")
    incluir_prompt: bool = Field(False, description="Return the exact prompt sent to the model (for documentation).")


class FuenteRAG(BaseModel):
    """Inventory document retrieved and injected into the prompt."""

    id_lote: int
    numero_lote: str
    medicamento: str
    dias_para_vencer: int
    nivel_alerta: str | None
    puntaje: float = Field(..., description="BM25 + urgency relevance score.")


class UsoTokens(BaseModel):
    input_tokens: int
    output_tokens: int
    thinking_tokens: int = Field(0, description="Internal reasoning tokens, billed at the output price.")
    total_tokens: int


class ConsultaIAResponse(BaseModel):
    """Grounded answer generated by the LLM plus usage and cost metrics."""

    model_config = ConfigDict(json_schema_extra={"examples": [{
        "respuesta": "- **LT-2026-077** (Amoxicilina 500 mg) — 30 unidades, vence en 8 días (CRÍTICO)...",
        "tecnica": "few_shot", "modelo": "gemini-3.8-flash",
        "fuentes": [{"id_lote": 7, "numero_lote": "LT-2026-077", "medicamento": "Amoxicilina 500 mg",
                     "dias_para_vencer": 8, "nivel_alerta": "CRITICA", "puntaje": 6.42}],
        "uso": {"input_tokens": 1450, "output_tokens": 180, "thinking_tokens": 320, "total_tokens": 1950},
        "latencia_ms": 2350, "costo_estimado_usd": 0.0029625, "prompt": None,
    }]})

    respuesta: str
    tecnica: Tecnica
    modelo: str
    fuentes: list[FuenteRAG]
    uso: UsoTokens
    latencia_ms: int
    costo_estimado_usd: float = Field(..., description="Estimated cost at paid-tier prices (USD).")
    prompt: str | None = None


class ContextoRAGResponse(BaseModel):
    """Retrieval step only (no LLM call, no cost): what the model would receive as context."""

    pregunta: str
    umbral_preventivo_dias: int
    contexto: str
    fuentes: list[FuenteRAG]


class ComparacionRequest(BaseModel):
    model_config = ConfigDict(json_schema_extra={"examples": [{
        "pregunta": "¿Hay medicamentos vencidos todavía en inventario? Indica lote y cantidad."}]})

    pregunta: str = Field(..., min_length=5, max_length=500)
    top_k: int = Field(8, ge=1, le=20)


class ComparacionResponse(BaseModel):
    """Same question answered with the three prompting techniques (3 LLM calls)."""

    pregunta: str
    resultados: list[ConsultaIAResponse]
